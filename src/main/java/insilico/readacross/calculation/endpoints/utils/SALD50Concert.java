    public SALD50Concert() throws InitFailureException {
        super(100+ RaEngine.DB_VALUE_TYPE_LD50, "Rules for rat LD50 (CONCERT REACH)");
    }
    
    
    @Override
    protected void BuildSAList() throws InitFailureException {

        int idx = 0;

        for (int i=0; i<SMARTS_ACTIVITY.length; i++) {
            Alert curSA = new Alert(BlockIndex, AlertEncoding.BuildAlertId(BlockIndex, (idx+1)));
            curSA.setName("LD50 alert no. " + (i+1));
            curSA.setDescription("Structural alert for LD50 " + SMARTS_ACTIVITY[i][1] + " compounds, defined by the SMARTS: " + SMARTS_ACTIVITY[i][0] );
            if (SMARTS_ACTIVITY[i][1].equalsIgnoreCase(NON_TOXIC))
                curSA.setBoolProperty(KEY_ALERT_LD50_NON_TOX, true);
            if (SMARTS_ACTIVITY[i][1].equalsIgnoreCase(NOT_VERY_TOXIC))
                curSA.setBoolProperty(KEY_ALERT_LD50_NON_VERY_TOX, true);
            if (SMARTS_ACTIVITY[i][1].equalsIgnoreCase(TOXIC))
                curSA.setBoolProperty(KEY_ALERT_LD50_TOX, true);
            if (SMARTS_ACTIVITY[i][1].equalsIgnoreCase(VERY_TOXIC))
                curSA.setBoolProperty(KEY_ALERT_LD50_VERY_TOX, true);
            Alerts.add(curSA);
            idx++;
        }


    }
    
    
    @Override
    protected void InitSMARTS() throws InitFailureException {

        int nFragments = SMARTS_ACTIVITY.length;
        SA = new Pattern[nFragments];

        for (int i=0; i<SMARTS_ACTIVITY.length; i++) {
            String s = SMARTS_ACTIVITY[i][0];
            SA[i] = SmartsPattern.create(s, DefaultChemObjectBuilder.getInstance()).setPrepare(false);
        }

    }

    
    @Override
    protected AlertList CalculateSAMatches() throws GenericFailureException {
        AlertList Res = new AlertList();
        
        try {

            int nFragments = SMARTS_ACTIVITY.length;
            
            for (int i=0; i<nFragments; i++) 
                if (SA[i].matches(CurMol.GetStructure()))
                    Res.add((Alert)Alerts.get(i).clone());
            
        } catch (CloneNotSupportedException | InvalidMoleculeException e) {
            return null;
        }
        
        return Res; 
    }


