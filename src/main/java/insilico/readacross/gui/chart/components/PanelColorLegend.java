    @Override
    public void paint(Graphics g) {
        super.paint(g); 
        int height = g.getClipBounds().height-5;
        int width = g.getClipBounds().width;
        float y = 5;
        Graphics2D g2d = (Graphics2D) g;
        Paint p;
        do{
            if (y/height < 0.5f)
                p = new Color(1, (float)(2*y/height), 0,1f);
            else
                p = new Color((float)(2-2*y/height), 1, 0,1f);   
            g2d.setPaint(p);
            g2d.fillRect(10, (int)y, width/4, 1);
            y++;
        }  while (y < height);
    }
    
