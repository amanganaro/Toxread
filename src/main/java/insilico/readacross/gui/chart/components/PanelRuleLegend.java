    private void labelTableMouseClicked(MouseEvent evt) {//GEN-FIRST:event_labelTableMouseClicked
        iRaObjectRule selectedRule;
        int row = labelTable.rowAtPoint(evt.getPoint());
        selectedRule = (iRaObjectRule) labelTable.getModel().getValueAt(row,1);
        Graph<iRaObject, String> graph = layout.getGraph();
        if(!graph.containsVertex(selectedRule)){
            System.out.println("Not in graph!");
        }
        else{
            PickedState<iRaObject> pickedVertexState = vv.getPickedVertexState();
            pickedVertexState.pick(oldSelectedRule, false);
            
        
            if (evt.getClickCount() == 1){
                pickedVertexState.pick(selectedRule, true);
                updateCoordinates(vv, pickedVertexState.getPicked());
            }
            if (evt.getClickCount() == numberOfClick){
                Point2D p1 = new Point();
                p1.setLocation(layout.getX(selectedRule),layout.getY(selectedRule));
                final double x = vv.getRenderContext().getMultiLayerTransformer().transform(p1).getX();
                final double y = vv.getRenderContext().getMultiLayerTransformer().transform(p1).getY();
                SwingUtilities.invokeLater(new Runnable() {
                    @Override
                    public void run() {
                        vv.dispatchEvent(new MouseEvent(vv,MouseEvent.MOUSE_PRESSED, 1,MouseEvent.BUTTON1, (int)x, (int)y, numberOfClick, false));
                        vv.dispatchEvent(new MouseEvent(vv,MouseEvent.MOUSE_CLICKED, 1,MouseEvent.BUTTON1, (int)x, (int)y, numberOfClick, false));
                        vv.dispatchEvent(new MouseEvent(vv,MouseEvent.MOUSE_RELEASED, 1,MouseEvent.BUTTON1, (int)x, (int)y, numberOfClick, false));
                    }   
                });
            }
            oldSelectedRule = selectedRule;
                    
        }
    }//GEN-LAST:event_labelTableMouseClicked
    
    public void setSelectedEntry(iRaObjectRule rule){
        int row = 0;
         for (int i = 0; i < labelTable.getRowCount(); i++)
                if (labelTable.getValueAt(i, 1).equals(rule))
                    row = i;
        ListSelectionModel selectionModel = labelTable.getSelectionModel();
        selectionModel.setSelectionInterval(row, row);
    }
    
