    // Inner class for mouse adapter - on click shows bigger mol viewer
    private class MolViewerMouseAdapter extends MouseAdapter {
    
        private final String SMILES;
        
        public MolViewerMouseAdapter(String SMILES) {
            this.SMILES = SMILES;
        }

        @Override
        public void mouseClicked(MouseEvent e) {
            if (e.getClickCount() == 2) {
                JFrame f = new frameMolViewer(SMILES);
                f.setVisible(true);
            }
        }
    }
    
    
    /**
     * Creates new form PanelSimilarMolecule
     */
    public PanelSimilarMolecule(String SMILES, String CAS, double Similarity, String Experimental) {
        initComponents();
        
        DecimalFormatSymbols InternationalSymbols =
            new DecimalFormatSymbols();
        InternationalSymbols.setDecimalSeparator('.');         
        java.text.DecimalFormat df3 = new java.text.DecimalFormat("0.###", InternationalSymbols);
        
        // Sets the molecule viewer
        MolViewer = new PanelMolViewer();
        jPanelViewer.setLayout(new GridLayout(1, 1));
        jPanelViewer.add(MolViewer);
        MolViewer.SetMolecule(SMILES);
        jPanelViewer.setCursor(Cursor.getPredefinedCursor(Cursor.HAND_CURSOR));
        jPanelViewer.addMouseListener(new MolViewerMouseAdapter(SMILES));
        
        // Sets labels
        jLabelCAS.setText(CAS);
        jLabelSMILES.setText(SMILES);
        jLabelSim.setText(df3.format(Similarity));
        jLabelExp.setText(Experimental);
    }

    
    
