    public frameInterpolation(iRaObjectInterpolation intData) {
        initComponents();

        // Set Chart
        if (intData == null) 
            Chart = null;
        else {
            Chart = new InterpolationChart(400, 300);
            Chart.DataSeries.add(intData.getDataset());
            Chart.ChartAxis.SetNameX(intData.getAxisXTitle());
            Chart.ChartAxis.SetNameY(intData.getAxisYTitle());

            jPanelChart.add(Chart);
            jPanelChart.repaint();
        }
        
        // Set Legend
        DecimalFormatSymbols InternationalSymbols = new DecimalFormatSymbols();
        InternationalSymbols.setDecimalSeparator('.');         
        DecimalFormat Df2digits = new DecimalFormat("0.##", InternationalSymbols);
        
        this.jLabelTarget.setText("Target molecule " + intData.GetTargetValue().getName() + 
                ": " + intData.GetTargetValue().getFormattedValue());
        
        DefaultTableModel model = (DefaultTableModel) jTableMolecules.getModel();
        for (int i=0; i<intData.getDataset().Count(); i++) {
            InterpolationDataPoint p = intData.getDataset().GetPoint(i);
            Object[] curRow = new Object[4];
            curRow[0] = p.GetMark();
            curRow[1] = Df2digits.format(p.GetCoordinates().X);
            curRow[2] = p.isExperimental()?"YES":"no";
            curRow[3] = Df2digits.format(p.GetCoordinates().Y);
            model.addRow(curRow);
        }
        
        jTableMolecules.getColumnModel().getColumn(1).setHeaderValue(intData.getAxisXTitle());
        jTableMolecules.getColumnModel().getColumn(3).setHeaderValue(intData.getAxisYTitle() + " (experimental)");
        
    }

    public InterpolationChart GetChart() {
        return this.Chart;
    }
    
    @Override
    public void paint(Graphics g) {
        super.paint(g);
        if (Chart != null)
            Chart.repaint();
    }    
    
    
