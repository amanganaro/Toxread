    public frameMolDetails(iRaObjectSimMolecule SimMol, iDBConnector DBConn) {
        initComponents();

        DecimalFormatSymbols InternationalSymbols =
            new DecimalFormatSymbols();
        InternationalSymbols.setDecimalSeparator('.');         
        java.text.DecimalFormat df3 = new java.text.DecimalFormat("0.###", InternationalSymbols);
        
        SimMolObj = SimMol;

        // Sets the molecule viewer
        MolViewer = new PanelMolViewer();
        jPanelMolViewer.setLayout(new GridLayout(1, 1));
        jPanelMolViewer.add(MolViewer);
        try {
            dbStructure st = DBConn.GetStructure(SimMolObj.getMolecule().Id);
            MolViewer.SetMolecule(st.SMILES);
        } catch (Exception ex) {
            MolViewer.SetMolecule("");
        }
        
        // Sets the additional info
        jTextAreaInfo.setText("");
        String MolName, MolCAS, MolSMILES, MolExp, MolAllExp;
        MolName = SimMolObj.getMolecule().CommonName;
        MolName = (MolName.isEmpty() ? "(no name)" : MolName);
        MolCAS = SimMolObj.getMolecule().CAS;
        MolCAS = (MolCAS.isEmpty() ? "(no name)" : MolCAS);
        try {
            dbStructure st = DBConn.GetStructure(SimMolObj.getMolecule().Id);
            MolSMILES = st.SMILES;
            MolSMILES = (MolSMILES.isEmpty() ? "(no name)" : MolSMILES);
        } catch (Exception e) { MolSMILES = "(no SMILES)"; }
        MolExp = SimMolObj.getFormattedExperimentalValue();
        jTextAreaInfo.append("Name: " + MolName + "\n");
        jTextAreaInfo.append("CAS: " + MolCAS + "\n");
        jTextAreaInfo.append("SMILES: " + MolSMILES + "\n");
        jTextAreaInfo.append("Similarity to target: " + df3.format(SimMolObj.getSimilarity()) + "\n\n");
        jTextAreaInfo.append("Experimental activity: " + MolExp + "\n\n");
        
        // Searches for additional values
        if (SimMol.hasAdditionalValues()) {
            for (RaAdditionalValue val : SimMol.getAdditionalValues()) {
                jTextAreaInfo.append(val.getName() + ": " + val.getFormattedValue() + "\n");
            }
            jTextAreaInfo.append("\n");
        }
        
        // Searches all experimental data available for the molecule
//        try {
//            ArrayList<DBValue> AllValues = DBAccessTools.GetValues(SimMolObj.getMolecule().GetDBConnector(), SimMolObj.getMolecule(), null);
//            MolAllExp = "";
//            for (DBValue curVal : AllValues) {
//                if (SimMolObj.getExperimentalValue().GetId() == curVal.GetId())
//                    continue;
//                MolAllExp += curVal.GetValueType().GetName() + ": " + curVal.GetFormattedValue() + "\n";
//            }
//            if (MolAllExp.length() == 0)
//                throw new DatabaseException();
//        } catch (DatabaseException ex) {
//            MolAllExp = "No data found";
//        }
//        
//        jTextAreaInfo.append("Other available experimental data: \n" + MolAllExp);
        
        // Sets the title
        String title = "Details of molecule " + MolCAS;
        jLabelInfo.setText(title);
        this.setTitle(title);
        
    }

